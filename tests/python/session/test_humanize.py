def test_humanize_and_ignore_mutually_exclusive(humanize_tokenizer, simple_score):
    req = GenerationRequest(tracks=[TrackPrompt(id=0, bars=[], humanize=True, ignore=True)])
    with pytest.raises(RequestValidationError, match="mutually exclusive"):
        validate_request(req, simple_score, humanize_tokenizer._vocab.config())


def test_humanize_and_autoregressive_mutually_exclusive(humanize_tokenizer, simple_score):
    req = GenerationRequest(
        tracks=[TrackPrompt(id=0, bars=[1], humanize=True, autoregressive=True)]
    )
    with pytest.raises(RequestValidationError, match="mutually exclusive"):
        validate_request(req, simple_score, humanize_tokenizer._vocab.config())


def test_humanize_requires_supports_humanize_capability(ghost_tokenizer, simple_score):
    """ghost_tokenizer's config has supports_humanize=false (the default)."""
    req = GenerationRequest(tracks=[TrackPrompt(id=0, bars=[1], humanize=True)])
    with pytest.raises(RequestValidationError, match="supports_humanize"):
        validate_request(req, simple_score, ghost_tokenizer._vocab.config())
